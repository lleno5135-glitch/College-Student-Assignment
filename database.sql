CREATE SCHEMA IF NOT EXISTS college_assignment;

CREATE TABLE IF NOT EXISTS users(
 userid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 fullname VARCHAR(120) NOT NULL,
 email VARCHAR(150) NOT NULL UNIQUE,
 passwordhash VARCHAR(200) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK(role IN ('Admin','Staff','Student')),
 isactive BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS assignments(
 assignmentid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(200) NOT NULL,
 subject VARCHAR(120) NOT NULL,
 description TEXT NOT NULL,
 duedate DATE NOT NULL,
 staffid INTEGER NOT NULL REFERENCES users(userid),
 createdat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS submissions(
 submissionid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 assignmentid INTEGER NOT NULL REFERENCES assignments(assignmentid),
 studentid INTEGER NOT NULL REFERENCES users(userid),
 filename VARCHAR(255) NOT NULL,
 storedname VARCHAR(255) NOT NULL,
 submittedat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 status VARCHAR(30) NOT NULL DEFAULT 'Submitted'
);
